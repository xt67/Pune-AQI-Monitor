"""Live Pune air-quality and weather dashboard, backed by public forecast APIs."""
import sys
from pathlib import Path
import pandas as pd
import streamlit as st

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.data.live_api import LOCATIONS, live_service, LiveDataUnavailable

st.set_page_config(page_title="Pune Air Quality Sentinel", page_icon="🌿", layout="wide")
st.title("🌿 Pune Air Quality Sentinel")
st.markdown("Air quality and weather, refreshed from live forecast APIs.")
location = st.sidebar.selectbox("Pune location", list(LOCATIONS), format_func=lambda key: LOCATIONS[key][0])
hours = st.sidebar.select_slider("Hourly outlook", options=[12,24,48,72], value=24)
st.sidebar.caption("Automatically checks for fresh data every 15 minutes while this page is open.")
st.sidebar.markdown("[Open-Meteo](https://open-meteo.com/) · [CAMS](https://atmosphere.copernicus.eu/)")
st.sidebar.caption("US EPA AQI scale. Regional model estimates; not CPCB station measurements.")


def display_value(value, suffix=""):
    return "Unavailable" if value is None else f"{value:.1f}{suffix}"


@st.fragment(run_every=900)
def live_view():
    try:
        with st.spinner("Checking live forecast..."):
            result = live_service.forecast(location, hours)
    except LiveDataUnavailable as exc:
        st.error(str(exc))
        st.info("The provider may be temporarily unavailable or rate-limited. Retry in a few minutes.")
        return
    if result["stale"]:
        st.warning("Provider unavailable. Showing a cached forecast less than two hours old; see retrieval time below.")
    retrieved = pd.Timestamp(result["fetched_at"]).tz_convert("Asia/Kolkata")
    rows = pd.DataFrame(result["hourly"])
    rows["timestamp"] = pd.to_datetime(rows.timestamp, utc=True).dt.tz_convert("Asia/Kolkata")
    first = result["hourly"][0]
    st.subheader(result["location"])
    st.caption(f"Retrieved {retrieved.strftime('%d %b %Y, %H:%M IST')} · {result['cache_age_seconds']//60} minutes ago · forecast slots include the current hour")
    a,b,c,d = st.columns(4)
    a.metric("US AQI · current-hour estimate", display_value(first["us_aqi"]))
    b.metric("PM₂.₅", display_value(first["pm2_5"], " µg/m³"))
    c.metric("Temperature", display_value(first["temperature_2m"], " °C"))
    d.metric("Wind", display_value(first["wind_speed_10m"], " km/h"))
    outlook, weather, table = st.tabs(["Air quality outlook", "Weather outlook", "Hourly data"])
    with outlook:
        st.line_chart(rows.set_index("timestamp")[["us_aqi"]], y_label="US AQI")
        st.line_chart(rows.set_index("timestamp")[["pm2_5","pm10"]], y_label="µg/m³")
    with weather:
        st.line_chart(rows.set_index("timestamp")[["temperature_2m"]], y_label="°C")
        st.line_chart(rows.set_index("timestamp")[["relative_humidity_2m","precipitation_probability"]], y_label="%")
    with table:
        st.dataframe(rows, hide_index=True, use_container_width=True)
        st.download_button("Download forecast CSV", rows.to_csv(index=False), f"paqs-{location}.csv", "text/csv")
    st.map(pd.DataFrame({"lat":[result["latitude"]],"lon":[result["longitude"]]}), zoom=10)
    st.caption(result["limitations"])
    st.caption("Missing provider values remain unavailable; they are never replaced with random numbers.")

live_view()
with st.expander("Sources, refresh policy and project history"):
    st.markdown("""
Data: [Open-Meteo weather](https://open-meteo.com/en/docs) and
[Open-Meteo / CAMS air quality](https://open-meteo.com/en/docs/air-quality-api).
The public API needs no key for non-commercial use, subject to
[provider limits and terms](https://open-meteo.com/en/terms).

Forecasts are cached for 15 minutes. During an outage, a previously fetched
forecast may be displayed for up to two hours with a visible stale-data label.
Provider retrieval time is shown; it is not the model's issuance time.

The original LSTM, ARIMA and ST-GNN research code remains available in the
repository. Its historical scores are not live validation results. This dashboard
uses provider forecasts and does not claim they were generated by those models.
""")
